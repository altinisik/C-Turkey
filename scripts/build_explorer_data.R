# Regenerates explorer/data.js from the processed dataset.
#
# The online explorer reads data/processed/cturkey_v1.tsv directly, so this
# step is only needed for the offline copy: browsers block reading files when
# index.html is opened straight from disk, but they do allow <script> files.
# Run from the repository root after every change to the TSV:
#
#   Rscript scripts/build_explorer_data.R
#
# Uses base R only. The output is plain ASCII (non-ASCII characters are
# written as \uXXXX escapes), so it is identical on every OS and locale.

src <- "data/processed/cturkey_v1.tsv"
out <- "explorer/data.js"

tsv <- readChar(src, file.info(src)$size, useBytes = TRUE)
Encoding(tsv) <- "UTF-8"
cp <- utf8ToInt(tsv)
if (anyNA(cp)) stop(src, " is not valid UTF-8")

chr <- character(length(cp))
plain <- cp >= 32 & cp < 127 & !(cp %in% c(34, 92))   # printable, not " or \
chr[plain] <- intToUtf8(cp[plain], multiple = TRUE)
bmp <- !plain & cp < 65536
chr[bmp] <- sprintf("\\u%04x", cp[bmp])
astral <- !plain & cp >= 65536                          # surrogate pairs
if (any(astral)) {
  v <- cp[astral] - 65536
  chr[astral] <- sprintf("\\u%04x\\u%04x", 55296 + v %/% 1024, 56320 + v %% 1024)
}

js <- paste0(
  "// Generated by scripts/build_explorer_data.R from ", src, " on ", Sys.Date(), ".\n",
  "// Do not edit by hand.\n",
  "window.CTURKEY_TSV = \"", paste(chr, collapse = ""), "\";\n"
)
writeLines(js, out, sep = "", useBytes = TRUE)

message("Wrote ", out, " (", format(file.info(out)$size, big.mark = ","), " bytes)")
